function getAllGames() { return GAMES_DB; }
function getGameById(id) { return GAMES_DB.find(g => g.id === id); }
function getGamesByCategory(cat) {
  return cat === 'all' ? GAMES_DB : GAMES_DB.filter(g => g.cat === cat);
}
function getTopGames(n = 10) {
  return [...GAMES_DB].sort((a,b) => b.plays - a.plays).slice(0, n);
}
function getFeaturedGames() {
  return GAMES_DB.filter(g => g.featured).slice(0, 8);
}
function getNewGames(n = 8) {
  return GAMES_DB.filter(g => g.isNew).slice(0, n);
}
function getRelatedGames(game, n = 6) {
  return GAMES_DB
    .filter(g => g.cat === game.cat && g.id !== game.id)
    .sort((a,b) => b.plays - a.plays)
    .slice(0, n);
}
function searchGames(query) {
  const q = query.toLowerCase();
  return GAMES_DB.filter(g =>
    g.name.toLowerCase().includes(q) ||
    g.namePT.toLowerCase().includes(q) ||
    g.cat.includes(q) ||
    g.tags.some(t => t.includes(q)) ||
    g.desc.toLowerCase().includes(q)
  );
}

